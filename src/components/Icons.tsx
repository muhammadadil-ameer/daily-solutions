export function ToolIcon({ slug, category, ...p }: P & { slug: string; category: CategoryId }) {
  if (category === "image" && /resiz|compress|reduce/.test(slug)) return <ResizeIcon {...p} />;
  switch (category) {
    case "image":
      return <ImageIcon {...p} />;
    case "pdf":
      return <PdfIcon {...p} />;
    case "media":
      return <MediaIcon {...p} />;
    case "health":
      return <HeartIcon {...p} />;
  }
}
